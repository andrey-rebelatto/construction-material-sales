CREATE TABLE clientes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(11) NOT NULL UNIQUE
);
CREATE TABLE vendedores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 cpf VARCHAR(11) NOT NULL UNIQUE
);
CREATE TABLE produtos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 preco NUMERIC(12,2) NOT NULL CHECK (preco > 0)
);
CREATE TABLE vendas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 data_hora TIMESTAMP NOT NULL,
 cliente_id BIGINT NOT NULL REFERENCES clientes(id),
 vendedor_id BIGINT NOT NULL REFERENCES vendedores(id)
);
CREATE TABLE itens_venda (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 venda_id BIGINT NOT NULL REFERENCES vendas(id),
 produto_id BIGINT NOT NULL REFERENCES produtos(id),
 quantidade INTEGER NOT NULL CHECK (quantidade > 0 AND quantidade <= 1000000),
 preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario > 0),
 CONSTRAINT uk_venda_produto UNIQUE (venda_id, produto_id)
);
CREATE INDEX idx_vendas_cliente ON vendas(cliente_id);
CREATE INDEX idx_vendas_vendedor ON vendas(vendedor_id);
CREATE INDEX idx_itens_produto ON itens_venda(produto_id);
